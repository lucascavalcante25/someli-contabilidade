/** Remove entradas acidentalmente duplicadas por referência. */
function uniqByRef(list: MensagemLogin[]): MensagemLogin[] {
  const seen = new Set<string>();
  const out: MensagemLogin[] = [];
  for (const m of list) {
    const k = m.referencia.trim().toLowerCase();
    if (seen.has(k)) continue;
    seen.add(k);
    out.push(m);
  }
  return out;
}

const POOL = uniqByRef(MENSAGENS_LOGIN);

/** Monta texto com referência na mesma linha (NBSP). */
export function formatarMensagemLogin(m: MensagemLogin): string {
  const base = m.texto.trim();
  const comPonto = /[.!?…]$/.test(base) ? base : `${base}.`;
  const ref = m.referencia.trim().replace(/ /g, '\u00A0');
  return `${comPonto}\u00A0—\u00A0${ref}`;
}

/** Offset para não alinhar 1:1 com o ciclo da toolbar interna. */
export function indiceMensagemLogin(agora = new Date()): number {
  const start = new Date(agora.getFullYear(), 0, 0);
  const diff = agora.getTime() - start.getTime();
  const diaAno = Math.floor(diff / 86_400_000);
  return (diaAno + 97) % POOL.length;
}

export function mensagemLoginDoDia(agora = new Date()): MensagemLogin {
  return POOL[indiceMensagemLogin(agora)];
}

export function mensagemLoginPorIndice(i: number): MensagemLogin {
  const n = POOL.length;
  return POOL[((i % n) + n) % n];
}

export function totalMensagensLogin(): number {
  return POOL.length;
}
