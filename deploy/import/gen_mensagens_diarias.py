def sql_escape(s: str) -> str:
    return s.replace("'", "''")


def build_year() -> list[tuple[int, str, str, str]]:
    """Expande BASE até 366 dias, variando levemente textos repetidos."""
    out: list[tuple[int, str, str, str]] = []
    n = len(BASE)
    suffixes = [
        "",
        " Que esta verdade guie o seu dia.",
        " Medite nisto e ande em fé.",
        " Viva isso na prática, pela graça.",
        " Descanse nisso e siga firme.",
    ]
    for day in range(1, 367):
        texto, ref, tipo = BASE[(day - 1) % n]
        # Evita colisão de texto idêntico no mesmo ciclo longo
        cycle = (day - 1) // n
        if cycle > 0 and tipo == "animo":
            suf = suffixes[cycle % len(suffixes)]
            if suf and not texto.endswith(suf.strip()):
                texto = f"{texto}{suf}"
        elif cycle > 0 and tipo == "citacao":
            texto = f"{texto} (para refletir hoje)"
        elif cycle > 0 and tipo == "versiculo":
            texto = f"{texto}"
        out.append((day, texto, ref, tipo))
    # Garante unicidade mínima de (dia_ano)
    assert len(out) == 366
    return out


def main() -> None:
    rows = build_year()
    lines = [
        "-- Mensagens diárias cristocêntricas (protestantes / reformadas / evangélicas)",
        "CREATE TABLE IF NOT EXISTS mensagem_diaria (",
        "  id BIGSERIAL PRIMARY KEY,",
        "  dia_ano INTEGER NOT NULL,",
        "  texto TEXT NOT NULL,",
        "  referencia VARCHAR(160),",
        "  tipo VARCHAR(30) NOT NULL DEFAULT 'versiculo',",
        "  ativo BOOLEAN NOT NULL DEFAULT TRUE,",
        "  CONSTRAINT uk_mensagem_diaria_dia UNIQUE (dia_ano),",
        "  CONSTRAINT ck_mensagem_diaria_dia CHECK (dia_ano BETWEEN 1 AND 366),",
        "  CONSTRAINT ck_mensagem_diaria_tipo CHECK (tipo IN ('versiculo', 'citacao', 'animo'))",
        ");",
        "",
        "CREATE INDEX IF NOT EXISTS idx_mensagem_diaria_ativo ON mensagem_diaria (ativo);",
        "",
        "COMMENT ON TABLE mensagem_diaria IS 'Uma mensagem cristocêntrica por dia do ano (1-366).';",
        "",
        "INSERT INTO mensagem_diaria (dia_ano, texto, referencia, tipo, ativo) VALUES",
    ]
    values = []
    for dia, texto, ref, tipo in rows:
        values.append(
            f"({dia}, '{sql_escape(texto)}', '{sql_escape(ref)}', '{tipo}', TRUE)"
        )
    lines.append(",\n".join(values) + ";")
